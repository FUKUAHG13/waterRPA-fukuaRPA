"""HostView — 控制器与宿主窗口之间的稳定接口协议（P5b-1）。

本文件把“控制器经 self.host.<成员> 访问宿主”的既有耦合面，正式化为一个
runtime_checkable 的 Protocol。它不引入任何运行时行为变化，仅作为类型契约：
控制器 __init__(host: HostView) 因此依赖接口而非具体的 RPAWindow；
测试可用实现了全部成员的 StubHost 在无 GUI 环境下实例化控制器。

后续 P5b-3 会把其中私有态（_profiles_* 等）与直操作 Qt 控件的成员，
收口为意图明确的公开协议方法，并同步收窄本协议。
"""
